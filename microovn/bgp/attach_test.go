func TestParseNorthdVersion(t *testing.T) {
	cases := []struct {
		in        string
		wantMajor int
		wantMinor int
		wantOK    bool
	}{
		{"26.03.0-20.04.1", 26, 3, true},
		{"24.03.0-34.24.0-98.1", 24, 3, true},
		{"25.09.1", 25, 9, true},
		{"", 0, 0, false},
		{"garbage", 0, 0, false},
		{"26", 0, 0, false},
	}
	for _, c := range cases {
		major, minor, ok := parseNorthdVersion(c.in)
		if major != c.wantMajor || minor != c.wantMinor || ok != c.wantOK {
			t.Errorf("parseNorthdVersion(%q) = (%d,%d,%v), want (%d,%d,%v)", c.in, major, minor, ok, c.wantMajor, c.wantMinor, c.wantOK)
		}
	}
}

func TestAttachInterfacesDeterministic(t *testing.T) {
	host1, ovs1 := attachInterfaces("external-port")
	host2, ovs2 := attachInterfaces("external-port")
	if host1 != host2 || ovs1 != ovs2 {
		t.Fatalf("attachInterfaces is not deterministic: (%s,%s) vs (%s,%s)", host1, ovs1, host2, ovs2)
	}
	if host1 == ovs1 {
		t.Fatalf("host and ovs interfaces must differ: %q", host1)
	}
	if !strings.HasPrefix(host1, "mp") || !strings.HasSuffix(host1, "b") {
		t.Fatalf("unexpected host interface name %q", host1)
	}
	if !strings.HasPrefix(ovs1, "mp") || !strings.HasSuffix(ovs1, "o") {
		t.Fatalf("unexpected ovs interface name %q", ovs1)
	}
}

func TestAttachBirdConfig(t *testing.T) {
	cfg := attachConfig{
		RouterID:       "192.0.2.1",
		LocalASN:       65101,
		AdvertiseTable: 42,
		LearnTable:     10,
		Targets: []attachTarget{
			{RouterPort: "external-port", Peers: []types.Peer{{Address: "fe80::1", ASN: 65002}, {Address: "fe80::2", ASN: 65003}}},
			{RouterPort: "other-port", Peers: []types.Peer{{Address: "fe80::1", ASN: 65004}}},
		},
	}
	bird := attachBirdConfig(cfg)

	if strings.Count(bird, "protocol bgp ") != 3 {
		t.Fatalf("expected 3 bgp protocols, got:\n%s", bird)
	}
	if strings.Count(bird, "protocol bfd") != 1 {
		t.Fatalf("expected 1 global bfd protocol, got:\n%s", bird)
	}
	if strings.Count(bird, "passive yes") != 3 {
		t.Fatalf("expected passive bfd on each of 3 bgp neighbors, got:\n%s", bird)
	}
	for _, want := range []string{
		"# Generated by microovn attach mode.",
		"router id 192.0.2.1;",
		"kernel table 42",
		"kernel table 10",
		`proto = "advertisements"`,
		"bgp_med = krt_metric;",
		"local as 65101",
		"neighbor fe80::1 as 65002",
		"protocol bfd {\n strict bind yes;",
		"bfd { passive yes; };",
	} {
		if !strings.Contains(bird, want) {
			t.Errorf("rendered config missing %q:\n%s", want, bird)
		}
	}

	host1, _ := attachInterfaces("external-port")
	host2, _ := attachInterfaces("other-port")
	if host1 == host2 {
		t.Fatal("different router ports must map to different interfaces")
	}
	if !strings.Contains(bird, `interface "`+host1+`"`) || !strings.Contains(bird, `interface "`+host2+`"`) {
		t.Fatalf("rendered config missing dedicated interfaces:\n%s", bird)
	}
}

func TestRoutingProtocolsHas(t *testing.T) {
	for _, tc := range []struct {
		val   string
		proto string
		want  bool
	}{
		{"BGP,BFD", "BGP", true},
		{"BGP,BFD", "BFD", true},
		{"BGP,BFD", "OSPF", false},
		{"BGP, BFD", "BFD", true},
		{"BFD,BGP", "BGP", true},
		{"BGP", "BFD", false},
		{"BGP", "BGP", true},
		{"", "BGP", false},
		{"BGP,BFD", "", false},
	} {
		if got := routingProtocolsHas(tc.val, tc.proto); got != tc.want {
			t.Errorf("routingProtocolsHas(%q, %q) = %v, want %v", tc.val, tc.proto, got, tc.want)
		}
	}
}

func TestLinkHasMaster(t *testing.T) {
	out := "2: mp12345678b@mp12345678o: <BROADCAST,MULTICAST,UP,LOWER_UP> mtu 1500 qdisc noqueue master ovnvrf10 state UP mode DEFAULT group default qlen 1000"
	if !linkHasMaster(out, "ovnvrf10") {
		t.Fatal("expected to find master ovnvrf10")
	}
	if linkHasMaster(out, "ovnvrf1") {
		t.Fatal("ovnvrf1 must not match master ovnvrf10")
	}
	if linkHasMaster("no master here", "ovnvrf10") {
		t.Fatal("expected no match when no master")
	}
}

func TestMappingContains(t *testing.T) {
	mapping := "att-ext=mp12345678b,other=thing"
	if !mappingContains(mapping, "att-ext", "mp12345678b") {
		t.Fatal("expected to find att-ext=mp12345678b")
	}
	if mappingContains(mapping, "att-ext", "wrong") {
		t.Fatal("expected no match for wrong value")
	}
	if mappingContains(mapping, "att", "mp12345678b") {
		t.Fatal("expected no match for partial key")
	}
}

func TestLinkHasAddress(t *testing.T) {
	out := "2: mp12345678b@mp12345678o: <BROADCAST,MULTICAST,UP,LOWER_UP> mtu 1500 qdisc noqueue state UP mode DEFAULT group default qlen 1000\n    link/ether 02:00:00:00:00:02 brd ff:ff:ff:ff:ff:ff"
	if !linkHasAddress(out, "02:00:00:00:00:02") {
		t.Fatal("expected to find MAC 02:00:00:00:00:02")
	}
	if linkHasAddress(out, "02:00:00:00:00:03") {
		t.Fatal("expected no match for a different MAC")
	}
	if linkHasAddress("no link/ether here", "02:00:00:00:00:02") {
		t.Fatal("expected no match when no link/ether")
	}
}
