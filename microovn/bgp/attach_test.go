func TestParseNorthdVersion(t *testing.T) {
	cases := []struct {
		in        string
		wantMajor int
		wantMinor int
		wantPatch int
		wantOK    bool
	}{
		{"26.03.0-20.04.1", 26, 3, 0, true},
		{"26.03.3-20.04.1", 26, 3, 3, true},
		{"24.03.0-34.24.0-98.1", 24, 3, 0, true},
		{"25.09.1", 25, 9, 1, true},
		{"26.03", 26, 3, 0, true},
		{"", 0, 0, 0, false},
		{"garbage", 0, 0, 0, false},
		{"26", 0, 0, 0, false},
	}
	for _, c := range cases {
		major, minor, patch, ok := parseNorthdVersion(c.in)
		if major != c.wantMajor || minor != c.wantMinor || patch != c.wantPatch || ok != c.wantOK {
			t.Errorf("parseNorthdVersion(%q) = (%d,%d,%d,%v), want (%d,%d,%d,%v)", c.in, major, minor, patch, ok, c.wantMajor, c.wantMinor, c.wantPatch, c.wantOK)
		}
	}
}

