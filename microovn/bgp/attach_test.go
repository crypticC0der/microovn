func TestAttachInterfacesDeterministic(t *testing.T) {
	host1, ovs1 := attachInterfaces("external-port")
	host2, ovs2 := attachInterfaces("external-port")
	if host1 != host2 || ovs1 != ovs2 {
		t.Fatalf("attachInterfaces is not deterministic: (%s,%s) vs (%s,%s)", host1, ovs1, host2, ovs2)
	}
	if host1 == ovs1 {
		t.Fatalf("host and ovs interfaces must differ: %q", host1)
	}
	if !strings.HasPrefix(host1, "mp") || !strings.HasSuffix(host1, "b") {
		t.Fatalf("unexpected host interface name %q", host1)
	}
	if !strings.HasPrefix(ovs1, "mp") || !strings.HasSuffix(ovs1, "o") {
		t.Fatalf("unexpected ovs interface name %q", ovs1)
	}
}

func TestAttachBirdConfig(t *testing.T) {
	cfg := attachConfig{
		RouterID:       "192.0.2.1",
		LocalASN:       65101,
		AdvertiseTable: 42,
		LearnTable:     10,
		Targets: []attachTarget{
			{RouterPort: "external-port", Peers: []types.Peer{{Address: "fe80::1", ASN: 65002}, {Address: "fe80::2", ASN: 65003}}},
			{RouterPort: "other-port", Peers: []types.Peer{{Address: "fe80::1", ASN: 65004}}},
		},
	}
	bird := attachBirdConfig(cfg)

	if strings.Count(bird, "protocol bgp ") != 3 {
		t.Fatalf("expected 3 bgp protocols, got:\n%s", bird)
	}
	if strings.Count(bird, "protocol bfd") != 1 {
		t.Fatalf("expected 1 global bfd protocol, got:\n%s", bird)
	}
	if strings.Count(bird, "passive yes") != 3 {
		t.Fatalf("expected passive bfd on each of 3 bgp neighbors, got:\n%s", bird)
	}
	for _, want := range []string{
		"# Generated by microovn attach mode.",
		"router id 192.0.2.1;",
		"kernel table 42",
		"kernel table 10",
		`proto = "advertisements"`,
		"bgp_med = krt_metric;",
		"local as 65101",
		"neighbor fe80::1 as 65002",
		"protocol bfd {\n strict bind yes;",
		"bfd { passive yes; };",
	} {
		if !strings.Contains(bird, want) {
			t.Errorf("rendered config missing %q:\n%s", want, bird)
		}
	}

	host1, _ := attachInterfaces("external-port")
	host2, _ := attachInterfaces("other-port")
	if host1 == host2 {
		t.Fatal("different router ports must map to different interfaces")
	}
	if !strings.Contains(bird, `interface "`+host1+`"`) || !strings.Contains(bird, `interface "`+host2+`"`) {
		t.Fatalf("rendered config missing dedicated interfaces:\n%s", bird)
	}
}

func TestAttachBirdConfigNumbered(t *testing.T) {
	cfg := attachConfig{
		RouterID:       "192.0.2.1",
		LocalASN:       65101,
		AdvertiseTable: 42,
		LearnTable:     10,
		Targets: []attachTarget{
			{
				RouterPort: "ext0",
				Peers:      []types.Peer{{Address: "10.0.0.2", ASN: 65002}},
				// LocalIP preserves host bits: .1/31 stays .1/31.
				LocalIP: netip.MustParsePrefix("10.0.0.1/31"),
			},
		},
	}
	bird := attachBirdConfig(cfg)

	if strings.Count(bird, "protocol bgp ") != 1 {
		t.Fatalf("expected 1 bgp protocol, got:\n%s", bird)
	}
	for _, want := range []string{
		"local 10.0.0.1;",
		"neighbor 10.0.0.2 as 65002;",
		"next hop self;",
		"bfd { passive yes; };",
	} {
		if !strings.Contains(bird, want) {
			t.Errorf("rendered config missing %q:\n%s", want, bird)
		}
	}
	// Numbered uplinks do not use the unnumbered `interface` directive nor the
	// IPv6 extended-next-hop mechanism.
	if strings.Contains(bird, "interface ") {
		t.Errorf("numbered uplink must not render an `interface` directive:\n%s", bird)
	}
	if strings.Contains(bird, "extended next hop") {
		t.Errorf("numbered uplink must not render extended-next-hop:\n%s", bird)
	}
}

func TestParseLrpNetworks(t *testing.T) {
	cases := []struct {
		in   string
		want []netip.Prefix
	}{
		{"", nil},
		{"[]", nil},
		{`["10.0.0.1/31"]`, []netip.Prefix{netip.MustParsePrefix("10.0.0.1/31")}},
		{
			`["10.0.0.1/30", "fdaa::1/64"]`,
			[]netip.Prefix{netip.MustParsePrefix("10.0.0.1/30"), netip.MustParsePrefix("fdaa::1/64")},
		},
	}
	for _, c := range cases {
		got, err := parseLrpNetworks(c.in)
		if err != nil {
			t.Fatalf("parseLrpNetworks(%q) error: %v", c.in, err)
		}
		if len(got) != len(c.want) {
			t.Fatalf("parseLrpNetworks(%q) = %d entries, want %d", c.in, len(got), len(c.want))
		}
		for i := range got {
			if got[i] != c.want[i] {
				t.Errorf("parseLrpNetworks(%q)[%d] = %s, want %s", c.in, i, got[i], c.want[i])
			}
		}
	}
	if _, err := parseLrpNetworks(`["10.0.0.1/31"`); err == nil {
		t.Error("expected error for unmatched bracket")
	}
	if _, err := parseLrpNetworks(`["not-an-ip/31"]`); err == nil {
		t.Error("expected error for non-IP entry")
	}
}

func TestClassifyNumbered(t *testing.T) {
	v6peer := types.Peer{Address: "fe80::1", ASN: 65002}
	cases := []struct {
		name       string
		networks   []netip.Prefix
		peers      []types.Peer
		wantNumber bool
		wantPrefix netip.Prefix
		wantErr    bool
	}{
		{"no peers", nil, nil, false, netip.Prefix{}, false},
		{"unnumbered v6 only", nil, []types.Peer{v6peer}, false, netip.Prefix{}, false},
		{
			"numbered /31",
			[]netip.Prefix{netip.MustParsePrefix("10.0.0.0/31")},
			[]types.Peer{{Address: "10.0.0.1", ASN: 65002}},
			true, netip.MustParsePrefix("10.0.0.0/31"), false,
		},
		{
			"numbered /30 keeps host bits",
			[]netip.Prefix{netip.MustParsePrefix("10.0.0.1/30")},
			[]types.Peer{{Address: "10.0.0.2", ASN: 65002}},
			true, netip.MustParsePrefix("10.0.0.1/30"), false,
		},
		{
			"peer outside all networks",
			[]netip.Prefix{netip.MustParsePrefix("10.0.0.0/31")},
			[]types.Peer{{Address: "10.0.1.1", ASN: 65002}},
			false, netip.Prefix{}, true,
		},
		{
			"peers spanning networks",
			[]netip.Prefix{
				netip.MustParsePrefix("10.0.0.0/31"),
				netip.MustParsePrefix("10.0.1.0/31"),
			},
			[]types.Peer{{Address: "10.0.0.1", ASN: 65002}, {Address: "10.0.1.1", ASN: 65003}},
			false, netip.Prefix{}, true,
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			prefix, numbered, err := classifyNumbered(c.networks, c.peers)
			if (err != nil) != c.wantErr {
				t.Fatalf("classifyNumbered err = %v, wantErr %v", err, c.wantErr)
			}
			if err != nil {
				return
			}
			if numbered != c.wantNumber || prefix != c.wantPrefix {
				t.Errorf("classifyNumbered = (%v, %s), want (%v, %s)", numbered, prefix, c.wantNumber, c.wantPrefix)
			}
		})
	}
}

func TestValidateAttachAddressing(t *testing.T) {
	mkp := func(addr string, asn uint32) types.Peer { return types.Peer{Address: addr, ASN: asn} }
	numPrefix := netip.MustParsePrefix("10.0.0.0/31")

	cases := []struct {
		name     string
		peers    []types.Peer
		localIP  netip.Prefix
		localASN uint32
		wantErr  bool
	}{
		{"empty peers", nil, netip.Prefix{}, 65101, true},
		{"zero asn", []types.Peer{mkp("fe80::1", 0)}, netip.Prefix{}, 65101, true},
		{"local asn collision", []types.Peer{mkp("fe80::1", 65101)}, netip.Prefix{}, 65101, true},
		{"valid unnumbered", []types.Peer{mkp("fe80::1", 65002)}, netip.Prefix{}, 65101, false},
		{"valid numbered /31", []types.Peer{mkp("10.0.0.1", 65002)}, numPrefix, 65101, false},
		{"v6 on numbered", []types.Peer{mkp("fe80::1", 65002)}, numPrefix, 65101, true},
		{"v4 on unnumbered", []types.Peer{mkp("10.0.0.1", 65002)}, netip.Prefix{}, 65101, true},
		{"peer outside prefix", []types.Peer{mkp("10.0.2.1", 65002)}, numPrefix, 65101, true},
		{"peer == local", []types.Peer{mkp("10.0.0.0", 65002)}, numPrefix, 65101, true},
		{"host route /32", []types.Peer{mkp("10.0.0.1", 65002)}, netip.MustParsePrefix("10.0.0.0/32"), 65101, true},
		{"local is /30 network addr", []types.Peer{mkp("10.0.0.2", 65002)}, netip.MustParsePrefix("10.0.0.0/30"), 65101, true},
		{"peer is /30 broadcast", []types.Peer{mkp("10.0.0.3", 65002)}, netip.MustParsePrefix("10.0.0.1/30"), 65101, true},
		{"valid /30", []types.Peer{mkp("10.0.0.2", 65002)}, netip.MustParsePrefix("10.0.0.1/30"), 65101, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			err := validateAttachAddressing(c.peers, c.localIP, c.localASN)
			if (err != nil) != c.wantErr {
				t.Fatalf("validateAttachAddressing err = %v, wantErr %v", err, c.wantErr)
			}
		})
	}
}

func TestIsIPv4NetOrBroadcast(t *testing.T) {
	prefix := netip.MustParsePrefix("10.0.0.0/30")
	cases := []struct {
		addr string
		want bool
	}{
		{"10.0.0.0", true}, // network
		{"10.0.0.3", true}, // broadcast
		{"10.0.0.1", false},
		{"10.0.0.2", false},
	}
	for _, c := range cases {
		if got := isIPv4NetOrBroadcast(netip.MustParseAddr(c.addr), prefix); got != c.want {
			t.Errorf("isIPv4NetOrBroadcast(%s, /30) = %v, want %v", c.addr, got, c.want)
		}
	}
	// /31 has no network/broadcast distinction.
	if isIPv4NetOrBroadcast(netip.MustParseAddr("10.0.0.0"), netip.MustParsePrefix("10.0.0.0/31")) {
		t.Error("expected /31 network address to be treated as a valid host")
	}
}

