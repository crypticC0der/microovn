// UnderlayConfig is the structured host/fabric underlay configuration driven by
// `microovn enable bird`. Only the uplink interfaces are required; the scalars
// are defaulted from the node name. It is node-local (not cluster config) and is
// persisted outside OVS and dqlite, so a standalone host (no OVS) and the hybrid
// DPU both read the same file.
type UnderlayConfig struct {
	// Uplinks are the host interfaces (e.g. "dpu1p1.100") the fabric sessions
	// run over. Required (>= 1); each must exist on the node.
	Uplinks []string `json:"uplinks" yaml:"uplinks"`
	// ASN is the local ASN for the fabric sessions (optional; RFC 6996
	// node-name hash default).
	ASN string `json:"asn,omitempty" yaml:"asn,omitempty"`
	// RouterID is the BIRD router id (optional; node-name hash default).
	RouterID string `json:"router_id,omitempty" yaml:"router_id,omitempty"`
	// ULA is the /48 prefix the deployment derives per-VLAN fabric subnets
	// from. Optional and reserved: v1 renders only the node's own loopback
	// (RTS_DEVICE) routes, not the derived subnets.
	ULA string `json:"ula,omitempty" yaml:"ula,omitempty"`
}

// underlayConfigKeys are the recognised `--config key=value` keys.
var underlayConfigKeys = map[string]bool{"asn": true, "router_id": true, "ula": true}

// parseUnderlayConfig builds an UnderlayConfig from the repeatable --uplink
// values and the optional --config key=value scalars, filling node-name
// defaults for the unset scalars. It validates uplink existence and scalar
// syntax.
func parseUnderlayConfig(node string, uplinks []string, raw map[string]string) (UnderlayConfig, error) {
	var uc UnderlayConfig

	for key := range raw {
		if !underlayConfigKeys[key] {
			return uc, fmt.Errorf("unknown underlay config key %q", key)
		}
	}

	uc.Uplinks = uplinks
	uc.ASN = strings.TrimSpace(raw["asn"])
	uc.RouterID = strings.TrimSpace(raw["router_id"])
	uc.ULA = strings.TrimSpace(raw["ula"])

	if uc.ASN == "" {
		uc.ASN = generateAsnFromNodeName(node)
	}
	if uc.RouterID == "" {
		uc.RouterID = generateBGPRouterID(node)
	}

	if err := validateUnderlayConfig(uc); err != nil {
		return UnderlayConfig{}, err
	}
	return uc, nil
}

// validateUnderlayConfig checks the resolved UnderlayConfig. It is called after
// defaults are applied so a defaulted value is validated too.
func validateUnderlayConfig(uc UnderlayConfig) error {
	if len(uc.Uplinks) == 0 {
		return errors.New("at least one --uplink interface is required")
	}
	for _, u := range uc.Uplinks {
		if u == "" {
			return errors.New("uplink interface name must not be empty")
		}
		if _, err := os.Stat("/sys/class/net/" + u); err != nil {
			return fmt.Errorf("uplink interface %q does not exist", u)
		}
	}

	asn, err := strconv.ParseUint(uc.ASN, 10, 32)
	if err != nil || asn == 0 {
		return fmt.Errorf("invalid ASN %q", uc.ASN)
	}

	if net.ParseIP(uc.RouterID) == nil || net.ParseIP(uc.RouterID).To4() == nil {
		return fmt.Errorf("invalid router_id %q (must be a dotted-quad IPv4)", uc.RouterID)
	}

	if uc.ULA != "" {
		prefix, err := netip.ParsePrefix(uc.ULA)
		if err != nil || !prefix.Addr().Is6() || prefix.Bits() != 48 {
			return fmt.Errorf("invalid ula %q (must be an IPv6 /48)", uc.ULA)
		}
	}
	return nil
}

// generateAsnFromNodeName derives a deterministic RFC 6996 private-use ASN from
// the node name, dqlite-free (mirrors generateBGPRouterID's md5-of-name
// approach). It has no uniqueness guarantee and changes if the node is renamed —
// the same caveat as generateBGPRouterID.
func generateAsnFromNodeName(node string) string {
	const rfc6996Min = uint64(4200000000)
	const rfc6996Max = uint64(4294967294)

	hash := md5.Sum([]byte(node))
	v := uint32(hash[0])<<24 | uint32(hash[1])<<16 | uint32(hash[2])<<8 | uint32(hash[3])
	asn := rfc6996Min + uint64(v)%(rfc6996Max-rfc6996Min+1)
	return strconv.FormatUint(asn, 10)
}

// underlayMarker is the header comment the underlay render emits so the
// reconciler can tell an underlay-generated config apart from the seed default.
const underlayMarker = "# Generated by microovn underlay mode."

// renderUnderlay renders the BIRD configuration for the structured underlay: a
// shared base (log/router-id/device), a neighbor peer-discovery table, one radv
// protocol that listens for the fabric toR's Router Advertisements and publishes
// the discovered link-local peers, one global strict-bind BFD per uplink, and one
// actively-connecting unnumbered IPv6 eBGP session per uplink. The node is the
// ACTIVE speaker: BIRD discovers the toR's link-local from its RAs and spawns a
// dynamic session to it; it advertises the node's own loopback routes
// (RTS_DEVICE) and imports everything. It is a pure function, like
// attachBirdConfig.
func renderUnderlay(uc UnderlayConfig) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s\nlog syslog all;\nrouter id %s;\nprotocol device {}\n", underlayMarker, uc.RouterID)
	b.WriteString("neighbor table peers;\n")
	b.WriteString(renderUnderlayRadv(uc))
	b.WriteString(renderUnderlayBfd(uc))
	for i, u := range uc.Uplinks {
		b.WriteString(renderUnderlayBgp(i, u, uc.ASN))
	}
	return b.String()
}

// renderUnderlayRadv renders the radv protocol that does peer discovery: it
// listens for Router Advertisements from the fabric toR on each uplink
// (router discovery) and publishes the discovered link-local peers into the
// "peers" neighbor table for the BGP protocols to connect to.
func renderUnderlayRadv(uc UnderlayConfig) string {
	var b strings.Builder
	b.WriteString("protocol radv {\n")
	for _, u := range uc.Uplinks {
		fmt.Fprintf(&b, " interface %q {\n  router discovery yes;\n  max ra interval 4;\n  min ra interval 3;\n };\n", u)
	}
	b.WriteString(" neighbors { table peers; export all; };\n}\n")
	return b.String()
}

// renderUnderlayBfd renders the global strict-bind BFD protocol with a
// per-uplink interface block.
func renderUnderlayBfd(uc UnderlayConfig) string {
	var b strings.Builder
	b.WriteString("protocol bfd {\n strict bind yes;\n")
	b.WriteString(underlayBfdInterfaces(uc))
	b.WriteString("}\n")
	return b.String()
}

// renderUnderlayBgp renders one active unnumbered IPv6 eBGP session for an
// uplink. It is keyed off the discovered peers: "dynamic name" + the "neighbors"
// channel (which imports the radv-discovered peers) makes BIRD spawn an
// established, actively-connecting session per discovered toR link-local.
func renderUnderlayBgp(i int, uplink, asn string) string {
	return fmt.Sprintf(`protocol bgp underlay_%d {
 local as %s;
 neighbor range fe80::/10 external;
 dynamic name "underlay_%d_peer_";
 neighbors { table peers; };
 interface %q;
 direct;
 ipv6 {
  import all;
  export filter { if source = RTS_DEVICE then accept; reject; };
 };
 bfd on;
}
`, i, asn, i, uplink)
}

// underlayComposeBlock renders the underlay protocols (minus the shared base
// singletons, which the attach render owns) for composition into the hybrid
// attach+underlay bird.conf.
func underlayComposeBlock(uc UnderlayConfig) string {
	var b strings.Builder
	b.WriteString("neighbor table peers;\n")
	b.WriteString(renderUnderlayRadv(uc))
	for i, u := range uc.Uplinks {
		b.WriteString(renderUnderlayBgp(i, u, uc.ASN))
	}
	return b.String()
}

// underlayBfdInterfaces renders the per-uplink BFD interface blocks for the
// shared strict-bind BFD protocol (used when composing with attach, which owns
// the protocol header).
func underlayBfdInterfaces(uc UnderlayConfig) string {
	var b strings.Builder
	for _, u := range uc.Uplinks {
		fmt.Fprintf(&b, " interface %q { min rx interval 100 ms; min tx interval 100 ms; multiplier 3; };\n", u)
	}
	return b.String()
}

// writeUnderlayConfig persists the resolved UnderlayConfig as JSON.
func writeUnderlayConfig(uc UnderlayConfig) error {
	data, err := json.MarshalIndent(uc, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal underlay config: %w", err)
	}
	if err := os.WriteFile(paths.UnderlayConfigFile(), data, 0o644); err != nil {
		return fmt.Errorf("failed to write underlay config: %w", err)
	}
	return nil
}

// readUnderlayConfig reads the persisted UnderlayConfig. The second return is
// false when the file is absent (no underlay configured).
func readUnderlayConfig() (UnderlayConfig, bool, error) {
	data, err := os.ReadFile(paths.UnderlayConfigFile())
	if err != nil {
		if os.IsNotExist(err) {
			return UnderlayConfig{}, false, nil
		}
		return UnderlayConfig{}, false, fmt.Errorf("failed to read underlay config: %w", err)
	}
	var uc UnderlayConfig
	if err := json.Unmarshal(data, &uc); err != nil {
		return UnderlayConfig{}, false, fmt.Errorf("failed to parse underlay config: %w", err)
	}
	return uc, true, nil
}

// EnableBird applies the structured underlay configuration (the `microovn
// enable bird` RPC). It resolves + validates + persists the config, then applies
// it mode-aware: while attach is active it triggers the attach reconciler
// (which composes the underlay under the attach render); while managed BGP is
// active it refuses (mutual exclusion); otherwise it applies the underlay-only
// render.
func EnableBird(ctx context.Context, s microTypes.State, uplinks []string, raw map[string]string) error {
	uc, err := parseUnderlayConfig(s.Name(), uplinks, raw)
	if err != nil {
		return err
	}
	if err := writeUnderlayConfig(uc); err != nil {
		return err
	}

	switchActive := switchServiceActive(ctx, s)
	if switchActive {
		attachActive, err := HasAttach(ctx, s)
		if err != nil {
			return fmt.Errorf("failed to check whether BGP attach mode is active: %w", err)
		}
		if attachActive {
			// Compose underlay under the live attach render via the reconciler;
			// applying underlay-only here would clobber the attach config.
			return ReconcileAttach(ctx, s)
		}

		managedActive, err := HasManagedBgp(ctx, s)
		if err != nil {
			return fmt.Errorf("failed to check whether managed BGP is active: %w", err)
		}
		if managedActive {
			return errors.New("underlay BGP and managed BGP are mutually exclusive")
		}
	}

	return applyBirdConfig(ctx, s, renderUnderlay(uc))
}
